    /// Generate a task plan from a high-level goal
    pub async fn plan_orchestration(&self, goal: &str, context: &PlannerContext) -> Result<TaskPlan> {
        // Build the planning request
        let planning_request = self.build_planning_request(goal, context)?;
        
        // Call Claude to generate the plan
        let plan_json = self.call_claude_for_planning(&planning_request).await?;
        
        // Parse the response into a TaskPlan
        let mut task_plan: TaskPlan = serde_json::from_value(plan_json)
            .context("Failed to parse task plan from Claude response")?;
        
        // Validate the plan
        self.validate_plan(&task_plan)?;
        
        // Optimize the plan
        self.optimize_plan(&mut task_plan)?;
        
        Ok(task_plan)
    }

    /// Validate a task plan
    pub fn validate_plan(&self, plan: &TaskPlan) -> Result<()> {
        // Check that all tasks have unique IDs
        let mut task_ids = HashSet::new();
        for task in &plan.tasks {
            if !task_ids.insert(&task.id) {
                anyhow::bail!("Duplicate task ID found: {}", task.id);
            }
        }

        // Validate dependencies
        for (task_id, deps) in &plan.dependencies {
            // Check that the task exists
            if !task_ids.contains(task_id) {
                anyhow::bail!("Dependency references non-existent task: {}", task_id);
            }
            
            // Check that all dependencies exist
            for dep in deps {
                if !task_ids.contains(dep) {
                    anyhow::bail!("Task {} depends on non-existent task: {}", task_id, dep);
                }
            }
        }

        // Check for circular dependencies
        if self.has_circular_dependencies(plan)? {
            anyhow::bail!("Circular dependencies detected in task plan");
        }

        // Validate task properties
        for task in &plan.tasks {
            if task.name.trim().is_empty() {
                anyhow::bail!("Task {} has empty name", task.id);
            }
            if task.goal.trim().is_empty() {
                anyhow::bail!("Task {} has empty goal", task.id);
            }
            if task.priority == 0 || task.priority > 10 {
                anyhow::bail!("Task {} has invalid priority: {}", task.id, task.priority);
            }
        }

        // Validate resource requirements
        if let Some(duration) = plan.estimated_duration_seconds {
            if duration == 0 {
                anyhow::bail!("Estimated duration cannot be zero");
            }
        }

        Ok(())
    }

    /// Optimize a task plan
    pub fn optimize_plan(&self, plan: &mut TaskPlan) -> Result<()> {
        // Sort tasks by priority and dependencies
        let sorted_order = self.topological_sort_with_priority(plan)?;
        
        // Reorder tasks based on optimal execution order
        let task_map: HashMap<String, PlannedTask> = plan.tasks
            .drain(..)
            .map(|t| (t.id.clone(), t))
            .collect();
        
        plan.tasks = sorted_order
            .into_iter()
            .filter_map(|id| task_map.get(&id).cloned())
            .collect();

        // Update metadata
        plan.metadata.planner_version = "1.0.0".to_string();
        plan.metadata.created_at = Utc::now();

        Ok(())
    }

