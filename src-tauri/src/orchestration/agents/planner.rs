/// Context provided to the planner for generating task plans
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlannerContext {
    /// Available agent types that can be assigned to tasks
    pub available_agents: Vec<AgentType>,
    /// Resource constraints for the orchestration
    pub resource_constraints: ResourceConstraints,
    /// Existing tasks and their status (for replanning scenarios)
    pub existing_tasks: Vec<Task>,
    /// Additional context or requirements
    pub additional_context: HashMap<String, Value>,
}

/// Types of agents available for task assignment
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgentType {
    pub name: String,
    pub capabilities: Vec<String>,
    pub model: String,
    pub description: String,
}

/// Resource constraints for planning
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResourceConstraints {
    /// Maximum number of concurrent tasks
    pub max_concurrent_tasks: usize,
    /// Maximum time allowed for the entire orchestration (in seconds)
    pub max_duration_seconds: Option<u64>,
    /// Available computational resources
    pub available_memory_gb: Option<f64>,
    pub available_cpu_cores: Option<usize>,
}

/// A structured task plan generated by the planner
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskPlan {
    /// The original goal that was decomposed
    pub goal: String,
    /// List of tasks in the plan
    pub tasks: Vec<PlannedTask>,
    /// Dependencies between tasks (task_id -> list of dependency task_ids)
    pub dependencies: HashMap<String, Vec<String>>,
    /// Estimated total duration in seconds
    pub estimated_duration_seconds: Option<u64>,
    /// Estimated resource requirements
    pub resource_requirements: ResourceRequirements,
    /// Success criteria for the overall plan
    pub success_criteria: Vec<String>,
    /// Metadata about the plan
    pub metadata: PlanMetadata,
}

/// A task within the plan
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlannedTask {
    /// Unique identifier for the task within this plan
    pub id: String,
    /// Human-readable name
    pub name: String,
    /// Detailed description of what the task should accomplish
    pub description: String,
    /// The specific goal/prompt for this task
    pub goal: String,
    /// Suggested agent type for this task
    pub suggested_agent: String,
    /// Expected inputs from parent tasks
    pub expected_inputs: Vec<ExpectedInput>,
    /// Expected outputs/artifacts this task will produce
    pub expected_outputs: Vec<ExpectedOutput>,
    /// Estimated duration in seconds
    pub estimated_duration_seconds: Option<u32>,
    /// Priority level (1-10, higher is more important)
    pub priority: u8,
    /// Whether this task can be retried on failure
    pub retriable: bool,
    /// Success criteria specific to this task
    pub success_criteria: Vec<String>,
}

/// Expected input from a parent task
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExpectedInput {
    pub name: String,
    pub input_type: String,
    pub from_task_id: String,
    pub description: String,
}

/// Expected output from a task
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExpectedOutput {
    pub name: String,
    pub output_type: String,
    pub description: String,
}

/// Resource requirements for the plan
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResourceRequirements {
    pub peak_memory_gb: Option<f64>,
    pub peak_cpu_cores: Option<usize>,
    pub total_compute_hours: Option<f64>,
}

