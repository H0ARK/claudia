    /// Check if the plan has circular dependencies
    fn has_circular_dependencies(&self, plan: &TaskPlan) -> Result<bool> {
        let mut graph = DiGraph::<String, ()>::new();
        let mut node_indices = HashMap::new();

        // Add all tasks as nodes
        for task in &plan.tasks {
            let idx = graph.add_node(task.id.clone());
            node_indices.insert(task.id.clone(), idx);
        }

        // Add edges for dependencies
        for (task_id, deps) in &plan.dependencies {
            if let Some(&to_idx) = node_indices.get(task_id) {
                for dep in deps {
                    if let Some(&from_idx) = node_indices.get(dep) {
                        graph.add_edge(from_idx, to_idx, ());
                    }
                }
            }
        }

        // Use topological sort to detect cycles
        Ok(toposort(&graph, None).is_err())
    }

    /// Perform topological sort with priority consideration
    fn topological_sort_with_priority(&self, plan: &TaskPlan) -> Result<Vec<String>> {
        let mut graph = DiGraph::<String, ()>::new();
        let mut node_indices = HashMap::new();
        let mut priority_map = HashMap::new();

        // Add all tasks as nodes
        for task in &plan.tasks {
            let idx = graph.add_node(task.id.clone());
            node_indices.insert(task.id.clone(), idx);
            priority_map.insert(task.id.clone(), task.priority);
        }

        // Add edges for dependencies
        for (task_id, deps) in &plan.dependencies {
            if let Some(&to_idx) = node_indices.get(task_id) {
                for dep in deps {
                    if let Some(&from_idx) = node_indices.get(dep) {
                        graph.add_edge(from_idx, to_idx, ());
                    }
                }
            }
        }

        // Perform topological sort
        let topo_order = toposort(&graph, None)
            .map_err(|_| anyhow::anyhow!("Circular dependency detected"))?;

        // Convert back to task IDs, considering priority within each level
        let mut result = Vec::new();
        let mut level_tasks = Vec::new();
        let mut current_depth = 0;

        for node_idx in topo_order {
            let task_id = &graph[node_idx];
            let depth = self.calculate_depth(&graph, node_idx, &node_indices);
            
            if depth > current_depth {
                // Sort tasks at the current level by priority
                level_tasks.sort_by_key(|id: &String| {
                    std::cmp::Reverse(priority_map.get(id).copied().unwrap_or(0))
                });
                result.extend(level_tasks.drain(..));
                current_depth = depth;
            }
            
            level_tasks.push(task_id.clone());
        }

        // Don't forget the last level
        level_tasks.sort_by_key(|id: &String| {
            std::cmp::Reverse(priority_map.get(id).copied().unwrap_or(0))
        });
        result.extend(level_tasks);

        Ok(result)
    }

    /// Calculate the depth of a node in the DAG
    fn calculate_depth(
        &self,
        graph: &DiGraph<String, ()>,
        node: NodeIndex,
        _node_indices: &HashMap<String, NodeIndex>,
    ) -> usize {
        let mut max_depth = 0;
        for edge in graph.edges_directed(node, petgraph::Direction::Incoming) {
            let parent_depth = self.calculate_depth(graph, edge.source(), _node_indices);
            max_depth = max_depth.max(parent_depth + 1);
        }
        max_depth
    }
