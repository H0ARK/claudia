    /// Build the planning request for Claude
    fn build_planning_request(&self, goal: &str, context: &PlannerContext) -> Result<String> {
        let mut request = format!("Please create a detailed task plan for the following goal:\n\n{}\n\n", goal);

        if !context.available_agents.is_empty() {
            request.push_str("Available agent types:\n");
            for agent in &context.available_agents {
                request.push_str(&format!(
                    "- {}: {} (capabilities: {})\n",
                    agent.name,
                    agent.description,
                    agent.capabilities.join(", ")
                ));
            }
            request.push_str("\n");
        }

        request.push_str("Resource constraints:\n");
        request.push_str(&format!(
            "- Max concurrent tasks: {}\n",
            context.resource_constraints.max_concurrent_tasks
        ));
        if let Some(duration) = context.resource_constraints.max_duration_seconds {
            request.push_str(&format!("- Max duration: {} seconds\n", duration));
        }
        if let Some(memory) = context.resource_constraints.available_memory_gb {
            request.push_str(&format!("- Available memory: {} GB\n", memory));
        }
        if let Some(cores) = context.resource_constraints.available_cpu_cores {
            request.push_str(&format!("- Available CPU cores: {}\n", cores));
        }

        if !context.existing_tasks.is_empty() {
            request.push_str("\nExisting tasks to consider:\n");
            for task in &context.existing_tasks {
                request.push_str(&format!(
                    "- {} ({}): {}\n",
                    task.name,
                    task.status,
                    task.description
                ));
            }
        }

        if !context.additional_context.is_empty() {
            request.push_str("\nAdditional context:\n");
            request.push_str(&serde_json::to_string_pretty(&context.additional_context)?);
        }

        Ok(request)
    }

